# QUESTÃO 6 > Utilizando um laço while, exiba os números de 10 até 1 em ordem decrescente. 

# Começa a contagem pelo número 10
numero = 10

# Repete enquanto o número for maior ou igual a 1
while numero >= 1:

    # Exibe o número atual
    print(numero)

    # Diminui 1 do número a cada repetição
    numero -= 1